void ntc_10k_b3950_init(void)
{
}

float ntc_10k_b3950_temperature_get(u16 adc_value)
{
    int i;
    float ntc_temp;

    if (adc_value >= adc_table[0])
    {
        return TEMP_MIN;
    }
    if (adc_value <= adc_table[TABLE_SIZE - 1])
    {
        return TEMP_MAX;
    }

    for (i = 0; i < TABLE_SIZE - 1; i++)
    {
        if (adc_value <= adc_table[i] && adc_value >= adc_table[i + 1])
        {
            break;
        }
    }

    ntc_temp = (TEMP_MIN + i) +
               (float)(adc_table[i] - adc_value) / (adc_table[i] - adc_table[i + 1]);

    return ntc_temp;
}
